/* The timesheet's range                                                      */
/* -------------------------------------------------------------------------- */

/**
 * The widest window a timesheet may be asked for, in days.
 *
 * A timesheet emits one row per employee per worked day, so its size is the
 * product of the range and the headcount — the only read in this feature that
 * is not one row per agent. A quarter is longer than any payroll period anybody
 * runs and keeps the worst case (roughly 92 × headcount) comfortably renderable.
 *
 * The preset ranges are all shorter than this; it exists for the custom picker,
 * where the natural mistake is a start date typed with the wrong year.
 */
export const MAX_TIMESHEET_DAYS = 92;

/**
 * The timesheet's period, from a query string.
 *
 * Built on `resolveRange`, so the presets, the day boundaries and the clamping
 * of a reversed custom pair are the same ones every other report in the portal
 * uses — the brief's daily / weekly / monthly / custom are its `today`,
 * `last7`, `last30` and `custom`. Anything unrecognised falls back to today,
 * exactly as it does there, because a report should not 400 an administrator
 * over a stale bookmark.
 *
 * The one thing added here is the ceiling: an over-long custom range is pulled
 * back to its last {@link MAX_TIMESHEET_DAYS} days rather than refused, so the
 * screen shows a period the reader can then correct instead of an error page.
 */
export function resolveTimesheetRange(
  params: URLSearchParams,
  today?: string,
): DateRange {
  const range = resolveRange(params.get("range"), params.get("from"), params.get("to"), today);
  if (range.days <= MAX_TIMESHEET_DAYS) return range;

  return resolveRange(
    "custom",
    addDays(range.toDay, -(MAX_TIMESHEET_DAYS - 1)),
    range.toDay,
    today,
  );
}


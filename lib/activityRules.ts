/* Formatting and small shared derivations                                    */
/* -------------------------------------------------------------------------- */

/**
 * The duration-weighted mean of a set of intervals.
 *
 * Weighted rather than a plain average of percentages, because the intervals in
 * a window are not all the same length once a client has merged two after a
 * hiccup — and an unweighted mean would let a 10-second interval count as much
 * as a 60-second one. `null` for an empty set rather than 0: "no activity was
 * observed" and "activity was observed and it was zero" are different facts,
 * and showing the first as 0% would report an agent who was never tracked as
 * having been idle all day.
 */
export function weightedActivity(
  intervals: readonly { durationSeconds: number; activityPercentage: number }[],
): number | null {
  let weighted = 0;
  let total = 0;

  for (const interval of intervals) {
    weighted += interval.activityPercentage * interval.durationSeconds;
    total += interval.durationSeconds;
  }

  return total === 0 ? null : Math.round(weighted / total);
}

/** `72` -> `72%`, `null` -> `—`. The one place the em dash is decided. */
export function formatActivity(value: number | null): string {
  return value === null ? "—" : `${value}%`;
}

/**
 * The band an activity figure falls in, for colouring a cell.
 *
 * Three bands and no more, with the thresholds named here so a screen cannot
 * invent its own. Deliberately not "good / bad": the labels are descriptive
 * because the figure is descriptive — see {@link activityPercentage}.
 */
export type ActivityBand = "none" | "low" | "moderate" | "high";

export function activityBand(value: number | null): ActivityBand {
  if (value === null) return "none";
  if (value < 25) return "low";
  if (value < 60) return "moderate";
  return "high";
}
